def main():
    parser = argparse.ArgumentParser(description="FASE 2a: Ejecutar HetSIREN")
    parser.add_argument("--dataset", required=True,
                        choices=ALL_DATASETS + ["all"],
                        help="Dataset a procesar")
    parser.add_argument("--gpu", default="0", help="GPU IDs (default: 0)")
    args = parser.parse_args()

    datasets = ALL_DATASETS if args.dataset == "all" else [args.dataset]

    results = {}
    for ds in datasets:
        ok = run_hetsiren(ds, args.gpu)
        results[ds] = "OK" if ok else "FAILED"

    log("\n=== RESUMEN HETSIREN ===")
    for name, status in results.items():
        log(f"  {name}: {status}")

    log("\nSiguiente paso: python scripts/04_run_cryodrgn.py --dataset ...")


if __name__ == "__main__":
    main()
